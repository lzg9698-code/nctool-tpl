#!/usr/bin/env python3
"""Report and remove one-off build directories under target/ (dry run by default).

Candidates are directories under target/ that are not protected, not referenced
by tracked docs or .claude/launch.json, and older than --days. Nothing is deleted
unless its name is listed explicitly with --delete.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import os
from pathlib import Path
import re
import shutil
import stat
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "target"

# Directories that are part of the supported local workflow.
PROTECTED = {
    "debug",
    "dependency-audit",
    "agent-tools",
    "agent-preview",
    "platform-default",
    "platform-math",
    "browser-agent",
    "tmp",
}
PROTECTED_PREFIXES = ("agent-", "platform-", "browser-")

# Only files describing the current workflow protect a directory. Dated records,
# review reports and archive pages cite old directories as evidence; that is not
# a reason to keep their build output. .claude/launch.json is deliberately absent:
# local preview configs are regenerated by scripts/dev/setup_agent_env.mjs and may
# still name directories that are no longer needed.
ACTIVE_FILES = (
    "AGENTS.md",
    "CLAUDE.md",
    "README.md",
    "docs/README.md",
    "docs/CONTRIBUTING.md",
    "docs/CODEX_DEVELOPMENT.md",
    "docs/SYSTEM_DESIGN.md",
    "docs/ARCHITECTURE.md",
    "启动UI.bat",
    "scripts/dev/setup_agent_env.mjs",
)
ARCHIVE_FILES = ("docs/archive", "memory")


def _names_in(path: Path) -> set[str]:
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return set()
    pattern = re.compile(r"target[/\\]([A-Za-z0-9_.-]+)")
    return {match.group(1).rstrip(".") for match in pattern.finditer(text)}


def referenced_names() -> tuple[set[str], set[str]]:
    """Return (active, historical) target/ directory names mentioned in the repo."""
    active: set[str] = set()
    for name in ACTIVE_FILES:
        active |= _names_in(ROOT / name)
    historical: set[str] = set()
    for base in ARCHIVE_FILES:
        path = ROOT / base
        if not path.is_dir():
            continue
        for file in path.rglob("*"):
            if file.is_file() and file.suffix in {".md", ".json", ".txt"}:
                historical |= _names_in(file)
    return active, historical - active


def directory_size(path: Path) -> int:
    total = 0
    for entry in path.rglob("*"):
        try:
            if entry.is_file() and not entry.is_symlink():
                total += entry.stat().st_size
        except OSError:
            continue
    return total


def newest_mtime(path: Path) -> float:
    newest = path.stat().st_mtime
    for entry in path.rglob("*"):
        try:
            newest = max(newest, entry.stat().st_mtime)
        except OSError:
            continue
    return newest


def is_protected(name: str) -> bool:
    return name in PROTECTED or name.startswith(PROTECTED_PREFIXES)


def human(size: int) -> str:
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if size < 1024:
            return f"{size:.1f} {unit}"
        size /= 1024
    return f"{size:.1f} PB"


def running_binaries() -> list[Path]:
    """Executable paths of nctool processes, so an in-use directory is never removed."""
    if sys.platform != "win32":
        try:
            output = subprocess.run(
                ["ps", "-eo", "comm="], capture_output=True, text=True, timeout=10
            ).stdout
        except (OSError, subprocess.SubprocessError):
            return []
        return [Path(line.strip()) for line in output.splitlines() if line.strip() == "nctool"]
    try:
        output = subprocess.run(
            [
                "powershell",
                "-NoProfile",
                "-Command",
                "@(Get-CimInstance Win32_Process -Filter \"Name='nctool.exe'\" | "
                "Select-Object -ExpandProperty ExecutablePath)",
            ],
            capture_output=True,
            text=True,
            timeout=30,
            encoding="utf-8",
            errors="replace",
        ).stdout
    except (OSError, subprocess.SubprocessError):
        return []
    return [Path(line.strip()) for line in output.splitlines() if line.strip()]


def scan(days: float) -> tuple[list[dict], list[dict]]:
    now = datetime.now(timezone.utc).timestamp()
    active, historical = referenced_names()
    in_use = running_binaries()
    candidates, kept = [], []
    for path in sorted(TARGET.iterdir()):
        if not path.is_dir() or path.is_symlink():
            continue
        name = path.name
        age_days = (now - newest_mtime(path)) / 86400
        size = directory_size(path)
        reason = None
        if is_protected(name):
            reason = "受保护"
        elif name in active:
            reason = "当前工作流引用"
        elif any(str(binary).lower().startswith(str(path.resolve()).lower()) for binary in in_use):
            reason = "有 nctool 进程正在使用"
        elif age_days < days:
            reason = f"最近 {age_days:.0f} 天内有修改"
        entry = {
            "name": name,
            "size": size,
            "age": age_days,
            "reason": reason,
            "historical": name in historical,
        }
        (kept if reason else candidates).append(entry)
    return candidates, kept


def remove(names: list[str], days: float) -> int:
    candidates, _ = scan(days)
    available = {entry["name"]: entry for entry in candidates}
    _, kept = scan(days)
    reasons = {entry["name"]: entry["reason"] for entry in kept}
    for name in names:
        if name in available:
            continue
        if not (TARGET / name).is_dir():
            print(f"跳过 {name}：target/ 下不存在该目录", file=sys.stderr)
        else:
            print(
                f"跳过 {name}：不是清理候选（{reasons.get(name, '受保护或未过期')}）",
                file=sys.stderr,
            )
    removed = 0
    failures: list[str] = []
    for name in names:
        entry = available.get(name)
        if entry is None:
            continue
        path = TARGET / name
        if path.is_symlink() or path.resolve().parent != TARGET.resolve():
            print(f"跳过 {name}：不是 target/ 下的普通目录", file=sys.stderr)
            continue
        try:
            force_remove(path)
        except OSError as error:
            print(f"未能完全删除 target/{name}：{error}", file=sys.stderr)
            failures.append(name)
            continue
        remaining = path.exists()
        if remaining:
            failures.append(name)
            print(f"未能完全删除 target/{name}：仍有内容被占用", file=sys.stderr)
            continue
        removed += entry["size"]
        print(f"已删除 target/{name}（{human(entry['size'])}）")
    print(f"共回收 {human(removed)}")
    if failures:
        print(
            "以下目录未能完全删除，可能有进程占用或只读属性：\n  "
            + "\n  ".join(failures),
            file=sys.stderr,
        )
        return 1
    return 0


def force_remove(path: Path) -> None:
    """Remove a build tree, including read-only files inside vendored .git dirs."""
    if sys.platform != "win32":
        shutil.rmtree(path)
        return

    def clear_readonly(func, target, _error):
        os.chmod(target, stat.S_IWRITE)
        func(target)

    shutil.rmtree(path, onexc=clear_readonly)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--days", type=float, default=7, help="先保留最近 N 天修改过的目录（默认 7）")
    parser.add_argument("--delete", nargs="+", metavar="NAME", help="删除这些候选目录（显式指定）")
    parser.add_argument(
        "--delete-candidates",
        action="store_true",
        help="删除当前全部候选目录；仍受保护名单与进程占用约束",
    )
    parser.add_argument("--json", action="store_true")
    options = parser.parse_args()

    if not TARGET.is_dir():
        print("target/ 不存在", file=sys.stderr)
        return 2
    if options.delete and options.delete_candidates:
        print("--delete 与 --delete-candidates 只能二选一", file=sys.stderr)
        return 2
    if options.delete_candidates:
        candidates, _ = scan(options.days)
        if not candidates:
            print("没有候选目录")
            return 0
        print(f"将删除 {len(candidates)} 个目录，共 {human(sum(e['size'] for e in candidates))}：")
        for entry in candidates:
            print(f"  target/{entry['name']}")
        return remove([entry["name"] for entry in candidates], options.days)
    if options.delete:
        return remove(options.delete, options.days)

    candidates, kept = scan(options.days)
    if options.json:
        import json

        print(
            json.dumps(
                {
                    "candidates": candidates,
                    "kept": kept,
                    "reclaimable": sum(entry["size"] for entry in candidates),
                },
                ensure_ascii=False,
                indent=2,
            )
        )
        return 0

    print(f"target/ 共 {len(candidates) + len(kept)} 个子目录（干跑，未删除任何内容）\n")
    print(f"候选（当前工作流未引用且超过 {options.days:g} 天）：")
    for entry in sorted(candidates, key=lambda item: item["size"], reverse=True):
        note = "（仅被历史记录提及）" if entry["historical"] else ""
        print(
            f"  {entry['name']:<32} {human(entry['size']):>10}  "
            f"{entry['age']:>5.0f} 天前修改{note}"
        )
    print(f"\n可回收约 {human(sum(entry['size'] for entry in candidates))}")
    print("\n保留：")
    for entry in sorted(kept, key=lambda item: item["size"], reverse=True)[:20]:
        print(f"  {entry['name']:<32} {human(entry['size']):>10}  {entry['reason']}")
    if len(kept) > 20:
        print(f"  …另有 {len(kept) - 20} 个")
    print(
        "\n确认后删除：\n"
        "  python scripts/dev/clean_targets.py --delete-candidates   # 全部候选\n"
        "  python scripts/dev/clean_targets.py --delete <名称> ...    # 指定目录"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
