"""Check resource fingerprints portably without compiling the UI."""
import hashlib
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]


class BuildUiTests(unittest.TestCase):
    @unittest.skipUnless(shutil.which("node"), "Node.js is required")
    def test_check_uses_portable_paths_and_detects_changed_sources(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / "scripts").mkdir()
            shutil.copy2(ROOT / "scripts/build_ui.mjs", root / "scripts/build_ui.mjs")
            ui = root / "ui"
            for path in ["dist", "src/nested"]:
                (ui / path).mkdir(parents=True)
            out = root / "cli/ui"
            out.mkdir(parents=True)
            digest = hashlib.sha256()
            for name in ["package.json", "package-lock.json", "tsconfig.json", "vite.config.ts", "index.html"]:
                value = b"{}" if name.endswith(".json") else b"fixture"
                (ui / name).write_bytes(value)
                digest.update(value)
            source = b"export const value = 1;"
            (ui / "src/nested/value.ts").write_bytes(source)
            digest.update(b"src/nested/value.ts")
            digest.update(source)
            for path in [ui / "dist/index.html", out / "index.html"]:
                path.write_bytes(b"fixture")
            (out / "source.sha256").write_bytes((digest.hexdigest() + "\n").encode("utf-8"))
            (out / "assets.rs").write_bytes(
                b'// Generated by scripts/build_ui.mjs. Do not edit.\npub const FILES: &[(&str, &str, &[u8])] = &[\n\n];\n'
            )
            command = [shutil.which("node"), str(root / "scripts/build_ui.mjs"), "--check"]
            result = subprocess.run(command, capture_output=True, text=True, encoding="utf-8")
            self.assertEqual(result.returncode, 0, result.stderr)
            (ui / "src/nested/value.ts").write_bytes(b"changed")
            changed = subprocess.run(command, capture_output=True, text=True, encoding="utf-8")
            self.assertNotEqual(changed.returncode, 0)
            self.assertIn("WebUI sources changed", changed.stderr)


    @unittest.skipUnless(shutil.which("node"), "Node.js is required")
    def test_fingerprint_ignores_line_endings(self):
        """A CRLF checkout and an LF checkout must record the same fingerprint."""
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / "scripts").mkdir()
            shutil.copy2(ROOT / "scripts/build_ui.mjs", root / "scripts/build_ui.mjs")
            ui = root / "ui"
            (ui / "src").mkdir(parents=True)
            (ui / "dist").mkdir()
            out = root / "cli/ui"
            out.mkdir(parents=True)
            digest = hashlib.sha256()
            for name in ["package.json", "package-lock.json", "tsconfig.json", "vite.config.ts", "index.html"]:
                value = b"{\n}\n" if name.endswith(".json") else b"fixture"
                (ui / name).write_bytes(value)
                digest.update(value)
            source = b"export const a = 1;\nexport const b = 2;\n"
            (ui / "src/value.ts").write_bytes(source)
            digest.update(b"src/value.ts")
            digest.update(source)
            for path in [ui / "dist/index.html", out / "index.html"]:
                path.write_bytes(b"fixture")
            (out / "source.sha256").write_bytes((digest.hexdigest() + "\n").encode("utf-8"))
            (out / "assets.rs").write_bytes(
                b'// Generated by scripts/build_ui.mjs. Do not edit.\npub const FILES: &[(&str, &str, &[u8])] = &[\n\n];\n'
            )
            command = [shutil.which("node"), str(root / "scripts/build_ui.mjs"), "--check"]
            ok = subprocess.run(command, capture_output=True, text=True, encoding="utf-8")
            self.assertEqual(ok.returncode, 0, ok.stderr)
            # Same text checked out with CRLF must not look like a source change.
            (ui / "src/value.ts").write_bytes(source.replace(b"\n", b"\r\n"))
            (ui / "package.json").write_bytes(b"{\r\n}\r\n")
            crlf = subprocess.run(command, capture_output=True, text=True, encoding="utf-8")
            self.assertEqual(crlf.returncode, 0, crlf.stderr)


if __name__ == "__main__":
    unittest.main()
